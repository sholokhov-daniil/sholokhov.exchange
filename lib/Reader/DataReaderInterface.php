<?php

namespace Sholokhov\Exchange\Reader;

use Sholokhov\Exchange\Exception\Reader\ReaderException;

/**
 * Интерфейс для получения данных из различных источников.
 *
 * Реализации могут извлекать данные из:
 * - локальных файлов
 * - HTTP/HTTPS (с авторизацией и без)
 * - FTP/SFTP
 * - SSH и других источников
 *
 * Интерфейс абстрагирует способ получения данных и предоставляет
 * единый доступ к содержимому в виде потока (stream).
 *
 * Важно:
 * - Метод read() должен возвращать поток, готовый к чтению с начала.
 * - Ответственность за закрытие потока лежит на вызывающем коде.
 * - Реализация может выбрасывать исключения в случае ошибок доступа.
 */
interface DataReaderInterface
{
    /**
     * Возвращает поток данных из источника.
     *
     * @return resource Поток для чтения данных
     * @throws ReaderException
     */
    public function read();
}